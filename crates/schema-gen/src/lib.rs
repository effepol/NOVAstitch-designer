//! NOVAstitch Designer, module a: the part of the public schema generated from
//! the Rust types of `filum-core` (feature `schema`). The part for `nova` and
//! for the fields only the interface knows is written by hand in
//! `schema/nsd.schema.json`, which refers to this one by its `$id`.

/// The `$id` the hand-written schema refers to.
pub const CORE_ID: &str = "urn:novastitch:schema:filum-core";

/// Where the generated schema is kept, from the repository's root.
pub const CORE_PATH: &str = "schema/filum-core.schema.json";

/// The JSON Schema (2020-12) of `filum_core::Document`, as committed in `schema/`.
pub fn core_schema() -> serde_json::Value {
    let mut schema = serde_json::to_value(schemars::schema_for!(filum_core::Document)).expect("the schema is JSON");
    let obj = schema.as_object_mut().expect("the schema is an object");
    obj.insert("$id".into(), CORE_ID.into());
    obj.insert(
        "$comment".into(),
        "Generated by crates/schema-gen from crates/core/src/model.rs (cargo run -p nova-schema-gen). Do not edit: the hand-written part is nsd.schema.json.".into(),
    );
    schema
}

/// The text of the file: indented, one line end at the end.
pub fn core_schema_text() -> String {
    format!("{}\n", serde_json::to_string_pretty(&core_schema()).expect("the schema is JSON"))
}
